  v_count := public._claim_update_uuid_column_if_exists('goalie_requests', 'requested_by', p_target_profile_id, p_claim_profile_id);
  v_total_reassigned := v_total_reassigned + v_count;
  v_count := public._claim_update_uuid_column_if_exists('goalie_ratings', 'rated_by', p_target_profile_id, p_claim_profile_id);
  v_total_reassigned := v_total_reassigned + v_count;
  v_count := public._claim_update_uuid_column_if_exists('draft_roster_confirmations', 'confirmed_by', p_target_profile_id, p_claim_profile_id);
  v_total_reassigned := v_total_reassigned + v_count;
  -- league_spare_pool has UNIQUE(league_id, player_id): reassign non-colliding rows, drop leftover duplicates.
  IF to_regclass('public.league_spare_pool') IS NOT NULL THEN
    UPDATE league_spare_pool SET player_id = p_target_profile_id
    WHERE player_id = p_claim_profile_id
      AND NOT EXISTS (
        SELECT 1 FROM league_spare_pool lsp2
        WHERE lsp2.player_id = p_target_profile_id
          AND lsp2.league_id = league_spare_pool.league_id
      );
    GET DIAGNOSTICS v_count = ROW_COUNT;
    v_total_reassigned := v_total_reassigned + v_count;
    DELETE FROM league_spare_pool WHERE player_id = p_claim_profile_id;
  END IF;

  UPDATE profiles SET
    full_name = COALESCE(NULLIF(trim(profiles.full_name), ''), v_claim_profile.full_name),
    phone = COALESCE(profiles.phone, v_claim_profile.phone),
    position = COALESCE(profiles.position, v_claim_profile.position),
    jersey_number = COALESCE(profiles.jersey_number, v_claim_profile.jersey_number),
    legacy_player_id = COALESCE(profiles.legacy_player_id, v_claim_profile.legacy_player_id),
    legacy_merge_completed_at = NOW(),
    pending_legacy_match_ids = '{}',
    updated_at = NOW()
  WHERE id = p_target_profile_id;

  UPDATE legacy_players
  SET matched_to_profile_id = p_target_profile_id,
      matched_at = NOW(),
      updated_at = NOW()
  WHERE matched_to_profile_id = p_claim_profile_id
     OR id = v_claim_profile.legacy_player_id;

  DELETE FROM profiles WHERE id = p_claim_profile_id;

  RETURN jsonb_build_object(
    'success', true,
    'total_reassigned', v_total_reassigned,
    'claimed_profile_deleted', p_claim_profile_id,
    'merged_into', p_target_profile_id
  );
EXCEPTION
  WHEN others THEN
    RAISE WARNING 'claim_rostered_player_profile failed: %', SQLERRM;
    RETURN jsonb_build_object('success', false, 'error', SQLERRM);
END;
$$;
